create table if not exists public.rose_messages (
  id bigint generated by default as identity primary key,
  name varchar(40) not null,
  city varchar(50),
  category varchar(20) not null check (category in ('Je soutiens','Je me bats','J’ai vaincu','En mémoire')),
  message varchar(360) not null,
  approved boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.rose_pledges (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now()
);
alter table public.rose_messages enable row level security;
alter table public.rose_pledges enable row level security;
create policy "Lecture des messages approuvés" on public.rose_messages for select using (approved = true);
create policy "Dépôt public en attente" on public.rose_messages for insert with check (approved = false);
create policy "Compter les engagements" on public.rose_pledges for select using (true);
create policy "Prendre un engagement" on public.rose_pledges for insert with check (true);
create index if not exists rose_messages_approved_date on public.rose_messages (approved, created_at desc);
